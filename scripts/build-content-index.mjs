// Scans src/topics/*/{index.ts,notes.ts,problems.ts} and emits src/data/contentIndex.ts —
// a small static lookup (summary, conspect headings, problem count) that pages can import
// without pulling each topic's full (code-split) content into their bundle. Regex-based
// on purpose: it only needs to read plain string literals out of otherwise-typed source,
// not evaluate it, so it needs no ts-node/tsx runtime.
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const topicsDir = join(__dirname, "..", "src", "topics");
const outFile = join(__dirname, "..", "src", "data", "contentIndex.ts");

function readIfExists(path) {
  try {
    return readFileSync(path, "utf8");
  } catch {
    return null;
  }
}

const slugs = readdirSync(topicsDir).filter((name) => statSync(join(topicsDir, name)).isDirectory());

const entries = [];
for (const slug of slugs) {
  const indexSrc = readIfExists(join(topicsDir, slug, "index.ts"));
  const notesSrc = readIfExists(join(topicsDir, slug, "notes.ts"));
  const problemsSrc = readIfExists(join(topicsDir, slug, "problems.ts"));
  if (!indexSrc || !notesSrc) continue; // not a real content topic (e.g. would be a future stub dir)

  const summaryMatch = indexSrc.match(/summary:\s*"((?:[^"\\]|\\.)*)"/);
  const summary = summaryMatch ? summaryMatch[1].replace(/\\"/g, '"') : "";

  const headings = [...notesSrc.matchAll(/type:\s*"heading",\s*content:\s*"((?:[^"\\]|\\.)*)"/g)].map((m) =>
    m[1].replace(/\\"/g, '"'),
  );

  const problemCount = problemsSrc ? [...problemsSrc.matchAll(/\bid:\s*"/g)].length : 0;

  entries.push({ slug, summary, headings, problemCount });
}

entries.sort((a, b) => a.slug.localeCompare(b.slug));

const body = entries
  .map(
    (e) =>
      `  ${JSON.stringify(e.slug)}: { summary: ${JSON.stringify(e.summary)}, headings: ${JSON.stringify(e.headings)}, problemCount: ${e.problemCount} },`,
  )
  .join("\n");

const output = `// AUTO-GENERATED by scripts/build-content-index.mjs — do not edit by hand.
// Regenerate with \`npm run gen:content-index\` (also runs automatically before \`npm run build\`).

export interface ContentIndexEntry {
  summary: string;
  headings: string[];
  problemCount: number;
}

export const contentIndex: Record<string, ContentIndexEntry> = {
${body}
};
`;

writeFileSync(outFile, output, "utf8");
console.log(`Wrote ${entries.length} topics to ${outFile}`);
